def bake_forms(name: str, doc: str) -> str:
    """Bake real local form posts into the auth documents on disk (the
    captured SPA forms have no action; the derive gate and the clone's own
    handlers need literal <form method=post action=...> markup)."""

    if name == "login":
        doc = doc.replace(
            '<form class="space-y-4">',
            '<form class="space-y-4" method="post" action="/login">',
            1,
        )
        inputs = list(re.finditer(r"<input ", doc))
        for match, extra in zip(inputs[:2],
                                ('name="username" ', 'name="password" ')):
            at = match.end()
            doc = doc[:at] + extra + doc[at:]
            inputs = list(re.finditer(r"<input ", doc))
        if _GSI_SLOT in doc:
            doc = doc.replace(
                _GSI_SLOT,
                '<div class="S9gUrf-YoZ4jf" style="position: relative;">'
                + GSI_BUTTON
                + "</div>",
                1,
            )
    elif name == "forgot-password":
        # the captured legacy endpoint is localized onto the clone handler
        doc = re.sub(
            r'action="/forum_mod_backup/[^"]*"',
            'action="/login/forgot-password"',
            doc,
            count=1,
        )
        if 'name="email"' not in doc:
            doc = doc.replace('<input type="email" ',
                              '<input type="email" name="email" ', 1)
    elif name == "signup-account-create":
        doc = re.sub(
            r"<form(?![^>]*action=)",
            '<form method="post" action="/signup/register"',
            doc,
            count=1,
        )
        if 'name="email"' not in doc:
            doc = doc.replace('<input id="email" ',
                              '<input id="email" name="email" ', 1)
    return doc


def build(pages: dict[str, str], out_dir: pathlib.Path, summary: dict) -> set[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    missing: set[str] = set()
    for checkpoint, name in pages.items():
        source = CAP_ROOT / checkpoint / "desktop" / "page.html"
        if not source.is_file():
            summary[name] = {"error": "missing capture"}
            continue
        report = {
            "rewritten": 0,
            "dropped_tags": [],
            "content_fallback_refs": [],
            "script_blocks_dropped": 0,
            "ld_json_dropped": 0,
            "first_party_localized": 0,
            "external_boundaries": [],
        }
        mapper = Mapper(report)
        rewritten = rewrite_document(source.read_text(), mapper, report)
        rewritten = bake_forms(name, rewritten)
        out_path = out_dir / f"{name}.html"
        out_path.write_text(rewritten)
        page_missing = sorted(
            ref
            for ref in static_refs(rewritten)
            if not (SITE / "clone" / ref.lstrip("/")).exists()
        )
        missing.update(page_missing)
        remote = remaining_remote(rewritten)
        summary[name] = {
            "bytes": out_path.stat().st_size,
            "rewritten_refs": report["rewritten"],
            "script_blocks_dropped": report["script_blocks_dropped"],
            "ld_json_dropped": report["ld_json_dropped"],
            "dropped_tags": sorted(set(report["dropped_tags"])),
            "content_fallback_refs": sorted(set(report["content_fallback_refs"])),
            "first_party_localized": report["first_party_localized"],
            "external_boundaries": sorted(set(report["external_boundaries"])),
            "missing_static_paths": page_missing,
            "remaining_remote_refs": remote[:40],
            "remaining_remote_count": len(remote),
        }
        print(
            f"  {name}: rewrote {report['rewritten']}, scripts-dropped "
            f"{report['script_blocks_dropped']}, missing {len(page_missing)}, "
            f"remote-left {len(remote)}"
        )
    return missing


def main() -> int:
    summary: dict = {}
    missing = build(PAGES, PAGES_OUT, summary)
    state_summary: dict = {}
    missing |= build(STATE_PAGES, EVIDENCE_OUT, state_summary)
    summary["_states"] = state_summary
    remote_total = sum(
        v.get("remaining_remote_count", 0)
        for section in (summary, state_summary)
        for v in section.values()
        if isinstance(v, dict)
    )
    summary["_totals"] = {
        "pages": len(PAGES),
        "state_pages": len(STATE_PAGES),
        "remaining_remote_total": remote_total,
        "missing_static_paths_union": sorted(missing),
    }
    (SITE / "clone" / "frontend" / "rewrite-report.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n"
    )
    return 0 if remote_total == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
