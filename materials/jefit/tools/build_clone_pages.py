def mirror_rel(url: str) -> str:
    """Renamed mirror-relative location for one source URL."""

    rel = local_relpath(url)
    return RENAMED_RELS.get(rel, rel)


def local_relpath(url: str) -> str:
    """host/path mirror location; identical rule to tools/capture_assets.py."""

    parts = urllib.parse.urlsplit(url)
    path = parts.path.lstrip("/") or "index"
    if path.endswith("/"):
        path += "index"
    if parts.query:
        digest = hashlib.sha256(parts.query.encode()).hexdigest()[:10]
        stem, dot, suffix = path.rpartition(".")
        path = f"{stem}.q{digest}.{suffix}" if dot else f"{path}.q{digest}"
    segments = []
    for segment in path.split("/"):
        if len(segment.encode()) > 140:
            stem, dot, suffix = segment.rpartition(".")
            digest = hashlib.sha256(segment.encode()).hexdigest()[:16]
            segment = (
                f"h{digest}.{suffix}" if dot and len(suffix) <= 8 else f"h{digest}"
            )
        segments.append(segment)
    return f"{parts.netloc}/{'/'.join(segments)}"


def _absolute(url: str) -> urllib.parse.SplitResult | None:
    value = html_lib.unescape(url.strip())
    if not value or value.startswith(("data:", "blob:", "about:", "#", "mailto:")):
        return None
    if value.startswith("//"):
        value = "https:" + value
    if value.startswith("/"):
        value = "https://www.jefit.com" + value
    if not value.startswith(("http://", "https://")):
        return None
    return urllib.parse.urlsplit(value)


class Mapper:
    def __init__(self, report: dict) -> None:
        self.report = report
        css_names = set()
        manifest = json.loads(
            (SITE / "source-assets" / "manifest.json").read_text()
        )
        for asset in manifest["assets"]:
            if asset.get("mime_type") == "text/css":
                rel = asset["runtime_path"].split(f"assets/{CAPTURE_ID}/", 1)[1]
                css_names.add(rel)
        self.css_rels = css_names

    def map_asset(self, url: str) -> str | None:
        parts = _absolute(url)
        if parts is None:
            return None
        host = parts.netloc.casefold()
        if host not in CAPTURED_HOSTS | CONTENT_HOSTS:
            return None
        rel = mirror_rel(
            urllib.parse.urlunsplit(("https", host, parts.path, parts.query, ""))
        )
        if rel in self.css_rels:
            return f"{CSS_PREFIX}/{rel}"
        if (ASSET_ROOT / rel).is_file():
            return f"{STATIC_PREFIX}/{rel}"
        if parts.path == "/_next/image" and parts.query:
            # Uncaptured optimizer variant whose ORIGINAL image is mirrored
            # (e.g. the exercise-rail originals): serve the original.
            source = urllib.parse.parse_qs(parts.query).get("url", [""])[0]
            if source:
                if source.startswith("/"):
                    source = f"https://www.jefit.com{source}"
                original_rel = mirror_rel(source)
                if (ASSET_ROOT / original_rel).is_file():
                    return f"{STATIC_PREFIX}/{original_rel}"
        if host in FIRST_PARTY_HOSTS and parts.path.startswith("/_next/"):
            # Uncaptured Next.js optimizer variant (a 2x/lazy width the
            # capture viewport never fetched): deterministic mirror path,
            # local 404 rather than an unresolvable route.
            self.report["content_fallback_refs"].append(
                html_lib.unescape(url.strip())[:120]
            )
            return f"{STATIC_PREFIX}/{rel}"
        if host in CONTENT_HOSTS:
            self.report["content_fallback_refs"].append(
                html_lib.unescape(url.strip())[:120]
            )
            return f"{STATIC_PREFIX}/{rel}"
        return None


def rewrite_document(html: str, mapper: Mapper, report: dict) -> str:
    def drop_script(match: re.Match) -> str:
        open_tag = match.group(0)[: match.group(0).find(">") + 1]
        if re.search(r'(?i)type\s*=\s*["\']application/ld\+json["\']', open_tag):
            report["ld_json_dropped"] += 1
        report["script_blocks_dropped"] += 1
        return ""

    def drop_or_keep(match: re.Match, kind: str) -> str:
        tag = match.group(0)
        if kind == "link":
            if re.search(
                r'(?i)\brel\s*=\s*["\'](?:preconnect|dns-prefetch)["\']', tag
            ) and re.search(r"""(?is)\bhref\s*=\s*["'](?:https?:)?//""", tag):
                report["dropped_tags"].append("link:network-hint")
                return ""
            if re.search(r'(?i)\bas\s*=\s*["\']script["\']', tag) or re.search(
                r'(?i)\brel\s*=\s*["\']modulepreload["\']', tag
            ):
                report["dropped_tags"].append("link:script-preload")
                return ""
        url_match = re.search(r"""(?is)(?:src|href)\s*=\s*["']([^"']+)["']""", tag)
        if not url_match:
            return tag
        url = url_match.group(1)
        if not REMOTE_VALUE.match(url.strip()):
            return tag
        parts = _absolute(url)
        host = parts.netloc.casefold() if parts else ""
        if (
            mapper.map_asset(url) is not None
            or host in FIRST_PARTY_HOSTS
            or host in CONTENT_HOSTS
        ):
            return tag
        report["dropped_tags"].append(f"{kind}:{url[:100]}")
        return ""

    html = SCRIPT_BLOCK.sub(drop_script, html)
    html = LINK_TAG.sub(lambda m: drop_or_keep(m, "link"), html)
    html = IFRAME_TAG.sub(lambda m: drop_or_keep(m, "iframe"), html)
    html = IMG_TAG.sub(lambda m: drop_or_keep(m, "img"), html)
    html = NAMESPACE_DECL.sub("", html)
    html = MICRODATA_IRI.sub("", html)

    def replace_attr(match: re.Match) -> str:
        attr, quote, value = match.group(1), match.group(2), match.group(3)
        if attr.casefold() in ("srcset", "imagesrcset"):
            chunks = []
            changed = False
            for chunk in value.split(","):
                chunk = chunk.strip()
                if not chunk:
                    continue
                pieces = chunk.split()
                mapped = mapper.map_asset(pieces[0])
                if mapped:
                    pieces[0] = mapped
                    changed = True
                chunks.append(" ".join(pieces))
            if changed:
                report["rewritten"] += 1
                return f'{attr}={quote}{", ".join(chunks)}{quote}'
            return match.group(0)
        mapped = mapper.map_asset(value)
        if mapped:
            report["rewritten"] += 1
            return f"{attr}={quote}{mapped}{quote}"
        return match.group(0)

    html = URL_ATTR.sub(replace_attr, html)

    def replace_css_url(match: re.Match) -> str:
        target = match.group(1).strip("'\"")
        mapped = mapper.map_asset(target)
        if mapped is None and REMOTE_VALUE.match(target):
            # Third-party CSS background (an injected widget stylesheet):
            # localize onto the deterministic mirror path — a local 404,
            # never a remote request.
            parts = _absolute(target)
            if parts is not None:
                mapped = f"{STATIC_PREFIX}/{mirror_rel(parts.geturl())}"
                report["content_fallback_refs"].append(target[:120])
        if mapped:
            report["rewritten"] += 1
            return f"url({mapped})"
        return match.group(0)

    def rewrite_css_scope(scope_match: re.Match) -> str:
        return re.sub(
            r"url\(\s*([^)]+?)\s*\)", replace_css_url, scope_match.group(0)
        )

    # CSS url() references are rewritten ONLY inside style attributes and
    # <style> blocks. Tailwind arbitrary-value class tokens
    # (class="bg-[url('/x.jpg')]") must stay byte-identical to their escaped
    # stylesheet selectors, so class attributes are never touched — the
    # matching stylesheet declaration is localized by build_localized_css.
    html = re.sub(r"(?is)<style\b[^>]*>.*?</style>", rewrite_css_scope, html)
    html = re.sub(
        r"""(?is)\bstyle\s*=\s*"[^"]*"|\bstyle\s*=\s*'[^']*'""",
        rewrite_css_scope,
        html,
    )

    # First-party absolute URLs (canonical, og:url, nav links) become local
    # paths on the clone origin.
    def strip_origin(match: re.Match) -> str:
        report["first_party_localized"] += 1
        return "/" + match.group(1).lstrip("/")

    html = re.sub(
        r"(?i)https?://(?:www\.)?jefit\.com/?([^\"'\s<>)\\]*)", strip_origin, html
    )
    html = re.sub(
        r"(?i)(?<![:\w/])//(?:www\.)?jefit\.com/?([^\"'\s<>)\\]*)",
        strip_origin,
        html,
    )

    # Remaining third-party navigation targets keep their visible affordance
    # but point at the local external-boundary route.
    def boundary(match: re.Match) -> str:
        url = match.group(3)
        parts = urllib.parse.urlsplit(html_lib.unescape(url), scheme="https")
        slug = re.sub(r"[^a-z0-9.-]+", "-", parts.netloc.casefold()) or "external"
        report["external_boundaries"].append(url[:90])
        return f"{match.group(1)}={match.group(2)}/external/{slug}{match.group(2)}"

    html = re.sub(
        r"""(?is)\b(href)\s*=\s*(["'])(https?://[^"']+|//[^"']+)\2""",
        boundary,
        html,
    )
    if RUNTIME_TAG not in html:
        html = html.replace("</body>", f"{RUNTIME_TAG}</body>", 1)
    return html


def static_refs(html: str) -> set[str]:
    refs = set(re.findall(r"/static/[^\s\"'<>),]+", html))
    return {urllib.parse.urldefrag(r.split("?", 1)[0])[0] for r in refs}


def remaining_remote(html: str) -> list[str]:
    """Runtime-loadable remote references, matching the diagnostics audit
    (src/href/action attributes and CSS url() — plain-text URLs inside page
    copy and DOCTYPE/profile metadata are never fetched)."""

    return sorted(
        set(
            re.findall(
                r"(?i)(?:src|href|action|url)\s*[=(:]\s*[\"']?\s*"
                r"(?:https?:)?//(?!localhost|127\.0\.0\.1)[a-z0-9.-]+\.[a-z]{2,}"
                r"[^\"'\s<>)\\]*",
                html,
            )
        )
    )


