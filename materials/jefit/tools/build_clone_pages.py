#!/usr/bin/env python3
"""Generate frozen clone page documents from the captured JEFIT source DOM.

For every anonymous checkpoint route the desktop ``page.html`` (rendered,
responsive, viewport-independent DOM) is rewritten so that every asset
reference resolves onto the vendored mirror under
``/static/assets/2026-08-18.jefit-r1/...`` and no remote URL survives into
shipped markup. Results land in ``clone/frontend/pages/<name>.html`` plus a
mechanical rewrite report.

Site policy (scope/implement-notes.md): the source is a client-rendered
Next.js SPA and the clone re-serves the *rendered* presentation, so every
``<script>`` block is dropped (SPA runtime, RSC payload, trackers alike) and
interaction is re-implemented clone-locally in ``/static/site/app.js``.

Mapping policy, purely mechanical:

1. Asset URLs (root-relative, first-party absolute, and captured third-party
   hosts) map onto the deterministic mirror location computed with the same
   ``local_relpath`` rule the capture harness used (query strings collapse to
   a sha256 ``.q<digest>`` suffix). If the payload exists on disk the
   reference is rewritten; content-host references whose payload was never
   fetched are still localized onto the deterministic path (they 404 locally
   instead of leaving the origin) and reported.
2. Mirrored stylesheets keep their byte-exact vendored copies; the documents
   reference *localized* CSS copies generated by build_localized_css.py under
   ``/static/css/...`` so url() references inside CSS resolve locally too.
3. Unmapped third-party link/img/iframe tags (trackers, widgets) are dropped;
   remaining third-party navigation hrefs become local ``/external/<slug>``
   boundary links.
"""
